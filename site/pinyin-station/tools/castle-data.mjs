#!/usr/bin/env node
/**
 * 课本对齐（站 9–12）的数据生成器。两步，都可重复运行：
 *   1. node tools/castle-data.mjs build <map.json>   读取只读的对照表（练习册审计产物，不在仓库里），只抽出通用拼音内容
 *      （每课的带调拼读结果、韵母/整体认读音节的四声行）写成 content/pinyin-station/textbook.json。
 *      不抄练习册的版面、插图、儿歌原文、词表。
 *   2. node tools/castle-data.mjs apply               把 textbook.json 合进 content/pinyin-station/bank.json：
 *      课次的课本课次/页码、题库音节（bank.syllables）、四声系列（bank.tone4）、新夸奖句。
 *      （不要重跑 seed-content.mjs：它会覆盖 bank.json 里后来人工审过的内容。）
 * 音节 id 沿用游戏约定：ü 写 v（lve4、vn2），jqx 后的 ü 写成 u（jue2），零声母 ui/iu/ie/in/un/ve/vn 保持写法（对应的真人文件是 wei/you/ye/yin/wen/yue/yun）。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const textbookPath = path.join(root, 'content/pinyin-station/textbook.json');
const bankPath = path.join(root, 'content/pinyin-station/bank.json');
/** 游戏“站” → 课本课次与页码（见 pinyin-castle-alignment §2.1）。站 13 = 课本第 14 课，第 17 页以后还没有。 */
const LESSONS = {
  1: { lesson: 1, pages: [1] }, 2: { lesson: 2, pages: [2, 10], also: 9 }, 3: { lesson: 3, pages: [3] }, 4: { lesson: 4, pages: [4] },
  5: { lesson: 5, pages: [5] }, 6: { lesson: 6, pages: [6] }, 7: { lesson: 7, pages: [7] }, 8: { lesson: 8, pages: [8, 9] },
  9: { lesson: 10, pages: [12] }, 10: { lesson: 11, pages: [13] }, 11: { lesson: 12, pages: [14, 15] }, 12: { lesson: 13, pages: [16] },
  13: { lesson: 14, pages: [], pending: true },
};
const STATION_OF_PAGE = { 12: 9, 13: 10, 14: 11, 15: 11, 16: 12 };
const PLAIN = { 'āáǎà': 'a', 'ēéěè': 'e', 'īíǐì': 'i', 'ōóǒò': 'o', 'ūúǔù': 'u', 'ǖǘǚǜü': 'v' };
const plain = (text) => [...text].map((c) => Object.entries(PLAIN).find(([marks]) => marks.includes(c))?.[1] ?? c).join('');
const MARKS = { a: 'āáǎà', e: 'ēéěè', i: 'īíǐì', o: 'ōóǒò', u: 'ūúǔù', v: 'ǖǘǚǜ' };
export const display = (id) => {
  const m = /^(.+)([0-4])$/.exec(id), raw = m[1].replaceAll('v', 'ü'), tone = Number(m[2]);
  if (!tone) return raw;
  const at = raw.includes('a') ? raw.indexOf('a') : raw.includes('e') ? raw.indexOf('e') : raw.includes('o') ? raw.indexOf('o') : Math.max(raw.lastIndexOf('i'), raw.lastIndexOf('u'), raw.lastIndexOf('ü'));
  const key = raw[at] === 'ü' ? 'v' : raw[at];
  return raw.slice(0, at) + MARKS[key][tone - 1] + raw.slice(at + 1);
};
const split = (id) => {
  const m = /^(zh|ch|sh|[bpmfdtnlgkhjqxzcsryw]?)([a-zv]+)([0-4])$/.exec(id);
  return { initial: m[1], final: m[2], tone: Number(m[3]) };
};

function build(mapFile) {
  const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
  const stations = {};
  for (const page of map.pages) {
    const station = STATION_OF_PAGE[page.page];
    if (!station) continue;
    const st = (stations[station] ??= { blends: [], series: [] });
    for (const s of page.sections) {
      if (s.type === 'blend') for (const b of s.items) st.blends.push({ id: b.id, three: b.kind === 'three' });
      if (s.type === 'tone4-final' || s.type === 'tone4-whole')
        for (const row of s.rows) {
          const series = plain(row[0]).replace(/[0-4]$/, '');
          st.series.push({ id: series, kind: s.type === 'tone4-whole' ? 'whole' : 'final', ids: [1, 2, 3, 4].map((t) => `${series}${t}`) });
        }
    }
  }
  // er: the only recording of the "first tone" id plays the second tone (see README), so a first-tone ēr cannot be played honestly yet.
  for (const st of Object.values(stations)) for (const s of st.series) if (s.id === 'er') s.skip = [1];
  const out = {
    version: 1,
    note: 'Generic 拼音 tables only (spellings, four-tone rows, which lesson/page they belong to). Generated by tools/castle-data.mjs from the exercise-book audit; no layout, text, pictures or word lists.',
    lessons: LESSONS,
    stations,
  };
  fs.writeFileSync(textbookPath, JSON.stringify(out, null, 2) + '\n');
  console.log('textbook.json:', Object.fromEntries(Object.entries(stations).map(([k, v]) => [k, `${v.blends.length} blends, ${v.series.length} series`])));
}

function apply() {
  const tb = JSON.parse(fs.readFileSync(textbookPath, 'utf8'));
  const bank = JSON.parse(fs.readFileSync(bankPath, 'utf8'));
  for (const l of bank.lessons) {
    const b = tb.lessons[l.id];
    if (b) l.book = b;
  }
  const have = new Set(bank.syllables.map((s) => s.id));
  let added = 0;
  const add = (id, lesson) => {
    if (have.has(id)) return;
    have.add(id);
    const p = split(id);
    bank.syllables.push({ id, display: display(id), initial: p.initial, final: p.final, tone: p.tone, lesson, audio: `py.syl.${id}` });
    added++;
  };
  bank.tone4 = [];
  for (const [station, st] of Object.entries(tb.stations)) {
    const lesson = Number(station);
    for (const b of st.blends) add(b.id, lesson);
    for (const s of st.series) {
      for (const [i, id] of s.ids.entries()) if (!(s.skip ?? []).includes(i + 1)) add(id, lesson);
      bank.tone4.push({ series: s.id, kind: s.kind, lesson, ids: s.ids, ...(s.skip ? { skip: s.skip } : {}) });
    }
  }
  for (const t of ['你听出了这个声调']) if (!bank.praise.includes(t)) bank.praise.push(t);
  finalizeBank(bank);
  fs.writeFileSync(bankPath, JSON.stringify(bank, null, 2) + '\n');
  console.log(`bank.json: +${added} syllables (now ${bank.syllables.length}), ${bank.tone4.length} tone series, praise ${bank.praise.length}`);
}

/**
 * 3. node tools/castle-data.mjs words <map.json>   阶段二 2a：站 9–12 的 32 个词 + 阶段复习页新增的 4 个词，以及站 9–12 字母卡的口诀。
 *    读只读的对照表，把词条（词 + 拼音 + 站 + 类型）直接散写进 bank.words、把词语音/口诀行追加进 yaml；仓库里不留整张词表。
 *    图一律是“汉字卡”（picture: 'text:<汉字>'）：渲染与题型在 2b 做，所以这些词先带 hold，不会被出成题。
 *    词的音节里不在题库的，补进 bank.syllables；没有真人录音的标 wordOnly（只作词的一部分，不出听辨/拼合题）。
 */
const MNEMONICS = { ai: '高矮高矮', ei: '水杯水杯', ui: '围巾围巾', ao: '棉袄棉袄', ou: '海鸥海鸥', iu: '优秀优秀', ie: '椰子椰子', ve: '月亮月亮', er: '耳朵耳朵', an: '天安门天安门', en: '摁门铃摁门铃', in: '音乐音乐', un: '温暖温暖', vn: '朵朵白云' };
const ACTIONS = new Set(['拖地', '擦玻璃', '提水', '回家', '围绕', '爬坡', '画图', '打嗝', '大哭', '坐下', '继续', '抓住', '数数', '批发', '哭了']);
const REUSE = { 吃西瓜: 'xigua', 白兔: 'tu', 回家: 'jia' }; // the book word shares its picture with an existing word: a text card keeps the one-picture-one-word rule
const STATION_OF_BOOK_PAGE = { 3: 3, 4: 4, 5: 5, 6: 6, 7: 7, 8: 8, 11: 8, 12: 9, 13: 10, 14: 11, 16: 12 };
/** The standard reading wins over a misprint in the book (打嗝 dǎ gé). */
const SANDHI = new Set(['打鼓', '水饺', '马匹', '祖母']);
/** Flags and lessons that must hold in every run: 3-3 words are marked (not asked where the child spells what they hear); a series' syllables carry the series' lesson. */
function finalizeBank(bank) {
  for (const w of bank.words) if (SANDHI.has(w.hanzi)) w.sandhi = true;
  for (const t of bank.tone4 ?? []) for (const id of t.ids) { const x = bank.syllables.find((s) => s.id === id); if (x && x.lesson !== t.lesson) x.lesson = t.lesson; }
}
/** Book words the content check (tools/check-content.mjs, plan §4.4: no sad words in narration) refuses. */
const LEFT_OUT = new Set(['哭了']);
const NORMATIVE = { 打嗝: ['da3', 'ge2'] };
function words(mapFile) {
  const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
  const bank = JSON.parse(fs.readFileSync(bankPath, 'utf8'));
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'public/audio/pinyin-station/audio-manifest.json'), 'utf8'));
  const yamlPath = path.join(root, 'content/narration/pinyin-station.yaml');
  const yaml = JSON.parse(fs.readFileSync(yamlPath, 'utf8'));
  const sylById = new Map(bank.syllables.map((x) => [x.id, x]));
  const added = [];
  for (const page of map.pages) {
    const station = STATION_OF_BOOK_PAGE[page.page];
    if (!station) continue;
    for (const sec of page.sections) {
      if (sec.type !== 'words') continue;
      for (const item of sec.items) {
        if (item.bankWordId) continue; // already in the game
        if (LEFT_OUT.has(item.hanzi)) continue; // the content check refuses 哭了 (the companion never sounds sad): the owner decides
        let w = item;
        const ids = NORMATIVE[w.hanzi] ?? w.syllableIds;
        w = { ...w, syllableIds: ids };
        let id = ids.map((x) => x.replace(/[0-4]$/, '')).join('');
        // another word (not a school word) already owns this id: keep both
        const clash = bank.words.find((x) => x.id === id && x.source !== '学校拼音练习');
        if (clash && clash.hanzi !== w.hanzi) id += '2';
        const reuse = REUSE[w.hanzi] && bank.words.find((x) => x.id === REUSE[w.hanzi]);
        const entry = {
          id,
          hanzi: w.hanzi,
          syllables: w.syllableIds,
          display: w.syllableIds.map(display).join(' '),
          picture: `text:${w.hanzi}`,
          kind: ACTIONS.has(w.hanzi) ? 'action' : w.hanzi === '吃西瓜' ? 'phrase' : 'noun',
          lesson: station,
          beyond: false,
          source: '学校拼音练习',
          semanticGroup: reuse?.semanticGroup ?? id,
        };
        // Askable only when the whole word has its own voice and every non-neutral syllable has its recording.
        const ready = manifest[`py.word.${id}`] && w.syllableIds.every((sid) => sid.endsWith('0') || manifest[`py.syl.${sid}`]);
        if (!ready) entry.hold = '等词语音和音节录音（到位后重跑 castle-data.mjs words 自动放开）';
        const at = bank.words.findIndex((x) => x.id === id && x.source === '学校拼音练习');
        if (at >= 0) bank.words[at] = entry;
        else bank.words.push(entry);
        added.push(entry);
        for (const sid of w.syllableIds) {
          const p = split(sid);
          const wordOnly = p.tone > 0 && !manifest[`py.syl.${sid}`];
          const known = sylById.get(sid);
          if (known) {
            if (known.wordOnly && !wordOnly) delete known.wordOnly;
            if (station < known.lesson) known.lesson = station; // a syllable is taught with the first word that uses it
            continue;
          }
          const syl = { id: sid, display: display(sid), initial: p.initial, final: p.final, tone: p.tone, lesson: station, audio: `py.syl.${sid}`, ...(wordOnly ? { wordOnly: true } : {}) };
          bank.syllables.push(syl);
          sylById.set(sid, syl);
        }
        if (!yaml.lines.some((l) => l.id === `py.word.${id}`)) yaml.lines.push({ id: `py.word.${id}`, role: 'companion', text: w.hanzi });
      }
    }
  }
  for (const l of bank.letters) if (MNEMONICS[l.id]) l.mnemonic = MNEMONICS[l.id];
  for (const [letter, text] of Object.entries(MNEMONICS)) {
    const line = yaml.lines.find((l) => l.id === `py.mnemonic.${letter}`);
    if (line) line.text = text;
    else yaml.lines.push({ id: `py.mnemonic.${letter}`, role: 'companion', text });
  }
  finalizeBank(bank);
  fs.writeFileSync(bankPath, JSON.stringify(bank, null, 2) + '\n');
  // The voice step edits the same yaml: only write it when this step really changed something.
  const nextYaml = JSON.stringify(yaml, null, 2) + '\n';
  if (nextYaml !== fs.readFileSync(yamlPath, 'utf8')) fs.writeFileSync(yamlPath, nextYaml);
  console.log(`bank.words: ${added.length} school words (now ${bank.words.length}); syllables now ${bank.syllables.length}; wordOnly ${bank.syllables.filter((x) => x.wordOnly).length}`);
}

/**
 * 4. node tools/castle-data.mjs stage3 <map.json>   阶段三：补站 1–8 的缺口 + 区分项 + 整体认读/单韵母四声 + 站 1–8 的课本式线索词。
 *    先跑 words（含站 3–8 的 42 个缺词），再补：带调拼读结果音节、单韵母/整体认读音节的四声系列（缺录音的声调自动 skip，系列不足 3 个声调就不出题）、
 *    9 个新区分对（最小对只用 manifest 里有真人音的音节）、站 1–8 字母卡的线索词。
 */
const TIP = {
  'd-p': ['左边这个，小肚子在左下；右边这个，小肚子在右上。', 'both'],
  'f-t': ['左边这个像一根弯弯的小拐杖；右边这个像一把直直的小伞把。', 'both'],
  'm-n': ['左边这个有两个门洞；右边这个只有一个门洞。', 'both'],
  'ai-ei': ['左边这个，嘴巴先张大再放松；右边这个，嘴巴扁扁的，像要笑。', 'both'],
  'ao-ou': ['左边这个，嘴巴从大大的慢慢变圆；右边这个，嘴巴从圆圆的慢慢变小。', 'both'],
  'ui-iu': ['左边这个，嘴巴先圆后扁；右边这个，嘴巴先扁后圆。', 'both'],
  'ie-ve': ['左边这个，嘴巴一直扁扁地笑着；右边这个，嘴巴先圆圆的再笑。', 'both'],
  'an-en': ['左边这个，嘴巴张得大一些；右边这个，嘴巴小一些。', 'both'],
  'in-un': ['左边这个，嘴巴扁扁地笑着；右边这个，嘴巴圆圆地噘着。', 'both'],
};
const SERIES = [
  // [series, kind, station, tones the book does not have]
  ['a', 'final', 1, []], ['e', 'final', 1, []], ['i', 'final', 2, []], ['u', 'final', 2, []],
  ['yi', 'whole', 2, []], ['wu', 'whole', 2, []], ['yu', 'whole', 2, []],
  ['zi', 'whole', 7, [2]], ['ci', 'whole', 7, []], ['si', 'whole', 7, [2]],
  ['zhi', 'whole', 8, []], ['chi', 'whole', 8, []], ['shi', 'whole', 8, []],
];
const stationOfLetter = { 1: ['a', 'o', 'e'], 2: ['i', 'u', 'v', 'y', 'w'], 3: ['b', 'p', 'm', 'f'], 4: ['d', 't', 'n', 'l'], 5: ['g', 'k', 'h'], 6: ['j', 'q', 'x'], 7: ['z', 'c', 's'], 8: ['zh', 'ch', 'sh', 'r'], 9: ['ai', 'ei', 'ui'], 10: ['ao', 'ou', 'iu'], 11: ['ie', 've', 'er'], 12: ['an', 'en', 'in', 'un', 'vn'] };
const lessonOf = (letter) => Number(Object.entries(stationOfLetter).find(([, l]) => l.includes(letter))?.[0] ?? 12);
function stage3(mapFile) {
  words(mapFile);
  const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
  const bank = JSON.parse(fs.readFileSync(bankPath, 'utf8'));
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'public/audio/pinyin-station/audio-manifest.json'), 'utf8'));
  const yamlPath = path.join(root, 'content/narration/pinyin-station.yaml');
  const yaml = JSON.parse(fs.readFileSync(yamlPath, 'utf8'));
  const have = new Map(bank.syllables.map((x) => [x.id, x]));
  const clip = (id) => !!manifest[`py.syl.${id}`];
  const addSyl = (id, lesson) => {
    const p = split(id);
    if (!/^(zh|ch|sh|[bpmfdtnlgkhjqxzcsryw]?)([a-zv]+)([1-4])$/.test(id)) return;
    let syl = have.get(id);
    if (!syl) {
      syl = { id, display: display(id), initial: p.initial, final: p.final, tone: p.tone, lesson, audio: `py.syl.${id}` };
      bank.syllables.push(syl);
      have.set(id, syl);
    } else if (lesson < syl.lesson && !syl.wordOnly === !clip(id)) syl.lesson = syl.lesson; // an existing syllable keeps its station
    if (!clip(id)) syl.wordOnly = true;
    else delete syl.wordOnly;
  };
  // 1. toned spelling results of the early lessons and the review page
  const stationOfPage = { 3: 3, 4: 4, 5: 5, 6: 6, 7: 7, 8: 8, 11: 8 };
  let blends = 0;
  for (const page of map.pages) {
    const st = stationOfPage[page.page];
    if (!st) continue;
    for (const sec of page.sections) if (sec.type === 'blend') for (const b of sec.items) if (b.toned) { addSyl(b.id, st); blends++; }
  }
  // 2. four-tone series (single vowels, whole-recognition syllables); tones without a recording are skipped automatically
  const book = new Map((bank.tone4 ?? []).map((t) => [t.series, t]));
  for (const [series, kind, lesson, notInBook] of SERIES) {
    const ids = [1, 2, 3, 4].map((t) => `${series}${t}`);
    for (const id of ids) if (!notInBook.includes(Number(id.at(-1))) ) addSyl(id, lesson);
    const prev = book.get(series);
    book.set(series, { series, kind, lesson, ids, ...(notInBook.length ? { bookSkip: notInBook } : {}) , ...(prev ? {} : {}) });
  }
  const bankSeries = new Map((bank.tone4 ?? []).map((t) => [t.series, t]));
  for (const [id, t] of book) bankSeries.set(id, t);
  const er = bankSeries.get('er');
  if (er) er.bookSkip = [1];
  for (const t of bankSeries.values()) {
    const skip = new Set(t.bookSkip ?? []);
    t.ids.forEach((id, n) => { if (!clip(id)) skip.add(n + 1); });
    if (skip.size) t.skip = [...skip].sort(); else delete t.skip;
  }
  bank.tone4 = [...bankSeries.values()];
  // a recording withdrawn later (ao4, see the importer's WITHHELD) leaves its syllable word-only, so no listening question can play a missing clip
  for (const syl of bank.syllables) if (syl.tone > 0 && !clip(syl.id)) syl.wordOnly = true;
  // 3. new confusion pairs; minimal pairs only from syllables that have a real recording
  // Curated minimal pairs (same everything but the contrast; real syllables only). Syllables without a recording yet are added as
  // word-only, so the pair switches itself on when the recording arrives and this step is run again.
  const MINIMAL = {
    'd-p': ['da1 pa1', 'da2 pa2', 'di1 pi1', 'dao3 pao3', 'dan4 pan4', 'du4 pu4'],
    'f-t': ['fa1 ta1', 'fa3 ta3', 'fu1 tu1', 'fu4 tu4', 'fan1 tan1', 'fang2 tang2'],
    'm-n': ['ma2 na2', 'ma3 na3', 'mi2 ni2', 'mu4 nu4', 'mai4 nai4'],
    'ai-ei': ['pai2 pei2', 'mai4 mei4', 'lai2 lei2', 'gai3 gei3', 'hai4 hei4', 'nai4 nei4'],
    'ao-ou': ['dao1 dou1', 'hao4 hou4', 'gao1 gou1', 'lao3 lou3', 'zao3 zou3', 'kao3 kou3'],
    'ui-iu': ['wei1 you1', 'wei2 you2', 'wei3 you3', 'wei4 you4'],
    'ie-ve': ['ye1 yue1', 'ye4 yue4', 'jie2 jue2', 'xie3 xue3', 'qie4 que4', 'lie4 lve4'],
    'an-en': ['ban1 ben1', 'pan2 pen2', 'man4 men4', 'fan1 fen1', 'zhan4 zhen4', 'shan1 shen1'],
    'in-un': ['yin1 wen1', 'yin2 wen2', 'yin3 wen3', 'yin4 wen4', 'jin1 jun1', 'qin2 qun2'],
  };
  const initialPairs = [['d', 'p'], ['f', 't'], ['m', 'n']], finalPairs = [['ai', 'ei'], ['ao', 'ou'], ['ui', 'iu'], ['ie', 've'], ['an', 'en'], ['in', 'un']];
  for (const [x, y] of [...initialPairs, ...finalPairs]) {
    const kind = initialPairs.some((q) => q[0] === x) ? 'initial' : 'final';
    const alias = (f) => (f === 've' ? 'ue' : f === 'vn' ? 'un' : f);
    const minimal = MINIMAL[`${x}-${y}`].map((q) => q.split(' '));
    const key = `${x}-${y}`;
    const [tip, focus] = TIP[key];
    const entry = { pair: [x, y], type: kind === 'initial' ? (['d', 'p'].includes(x) || ['f', 't'].includes(x) || ['m', 'n'].includes(x) ? 'shape' : 'initial') : 'final', minimalPairs: minimal, tip, focus };
    void alias;
    const at = bank.confusions.findIndex((c) => c.pair.join('-') === key);
    if (at >= 0) bank.confusions[at] = entry;
    else bank.confusions.push(entry);
    for (const pair of minimal) for (const id of pair) addSyl(id, Math.max(lessonOf(x), lessonOf(y)));
    const line = yaml.lines.find((l) => l.id === `py.tip.${key}`);
    if (line) line.text = tip;
    else yaml.lines.push({ id: `py.tip.${key}`, role: 'companion', text: tip });
  }
  // 4. cue words for the cards of stations 1-8 (short common phrases; the letter itself is spoken by the real recording)
  let cues = 0;
  for (const page of map.pages) {
    if (page.page > 10) continue;
    for (const sec of page.sections) {
      if (sec.type !== 'rhyme') continue;
      for (const it of sec.items) {
        const id = (it.letter ?? '').replace('ü', 'v');
        const letter = bank.letters.find((l) => l.id === id && l.lesson <= 8);
        if (!letter || /[A-Za-z]/.test(it.text)) continue;
        letter.mnemonic = it.text;
        const line = yaml.lines.find((l) => l.id === `py.mnemonic.${id}`);
        if (line) { line.text = it.text; delete line.norm; }
        else yaml.lines.push({ id: `py.mnemonic.${id}`, role: 'companion', text: it.text });
        cues++;
      }
    }
  }
  finalizeBank(bank);
  fs.writeFileSync(bankPath, JSON.stringify(bank, null, 2) + '\n');
  const nextYaml = JSON.stringify(yaml, null, 2) + '\n';
  if (nextYaml !== fs.readFileSync(yamlPath, 'utf8')) fs.writeFileSync(yamlPath, nextYaml);
  console.log(`stage3: ${blends} toned blend results, ${bank.tone4.length} tone series (${bank.tone4.filter((t) => t.ids.length - (t.skip?.length ?? 0) >= 3).length} playable), ${bank.confusions.length} confusions, ${cues} cue words; syllables ${bank.syllables.length}, wordOnly ${bank.syllables.filter((x) => x.wordOnly).length}`);
}

